    bool readIftitah = ((rekat == 1) || (isIkindiYatsi && rekat == 3)) && mezhep != Mezhep.maliki;
    if (readIftitah) {
      if (mezhep == Mezhep.shafii && rekat == 1) {
        arabic.writeln('[ВСТУПИТЕЛЬНАЯ МОЛЬБА ШАФИИ (ВАДЖДЖАХТУ)]');
        arabic.writeln('وَجَّهْتُ وَجْهِيَ لِلَّذِي فَطَرَ السَّمَاوَاتِ وَالْأَرْضَ حَنِيفًا وَمَا أَنَا مِنَ الْمُشْرِكِينَ ❁ إِنَّ صَلَاتِي وَنُسُكِي وَمَحْيَايَ وَمَمَاتِي لِلَّهِ رَبِّ الْعَالَمِينَ ❁ لَا شَرِيكَ لَهُ وَبِذَلِكَ أُمِرْتُ وَأَنَا مِنَ الْمُسْلِمِينَ');
        transcription.writeln('[Вступительная мольба Шафии (Ваджджахту)]');
        transcription.writeln('Ваджджахту ваджхия лиллязи фатарас-самавати валь-арда ханифан ва ма ана миналь-мушрикин. Инна саляти ва нусуки ва махяя ва мамати лилляхи раббиль-\'алямин. Ля шарика ляху ва бизалика умирту ва ана миналь-муслимин.');
        translation.writeln('[Перевод вступительной мольбы Шафии]');
        translation.writeln('Поистине, я обратил свое лицо к Тому, Кто сотворил небеса и землю, будучи ханифом, и я не из числа многобожников. Поистине, моя молитва, мое поклонение, моя жизнь и моя смерть принадлежат Аллаху, Господу миров. Нет у Него сотоварища. Это мне было повелено, и я из числа мусульман.');
      } else {
        arabic.writeln('[МОЛЬБА СУБХАНАКА]');
        arabic.writeln('سُبْحَانَكَ اللَّهُمَّ وَبِحَمْدِكَ ❁ وَتَبَارَكَ اسْمُكَ ❁ وَتَعَالَى جَدُّكَ ❁ وَلَا إِلَهَ غَيْرُكَ');
        transcription.writeln('[Мольба Субханака]');
        transcription.writeln('Субханакаллахумма ва бихамдика. Ва табаракасмука. Ва та\'аля джаддука. Ва ля иляха гайрук.');
        translation.writeln('[Перевод мольбы Субханака]');
        translation.writeln('Слава Тебе, о Аллах, и вся хвала. Благословенно имя Твое, и превознесено величие Твое. Нет божества, достойного поклонения, кроме Тебя.');
      }
      arabic.writeln('\n====================\n');
      transcription.writeln('\n----------------------------------------\n');
      translation.writeln('\n----------------------------------------\n');
    }

    arabic.writeln('[СУРА АЛЬ-ФАТИХА]');
    arabic.writeln('بِسْمِ اللّٰهِ الرَّحْمٰنِ الرَّح۪يمِ ❁ اَلْحَمْدُ لِلّٰهِ رَبِّ الْعَالَم۪ينَ ❁ اَلرَّحْمٰنِ الرَّح۪يمِ ❁ مَالِكِ يَوْmِ الدّ۪ينِ ❁ إِيَّاكَ نَعْبُدُ وَإِيَّاكَ نَسْتَع۪ينُ ❁ اِهْدِنَا الصِّرَاطَ الْمُسْتَق۪يمَ ❁ صِرَاطَ الَّذ۪ينَ أَنْعَمْتَ عَلَيْهِمْ غَيْرِ الْمَغْضُوبِ عَلَيْهِمْ وَلَا الضَّالّ۪ينَ');
    transcription.writeln('[Аль-Фатиха]');
    transcription.writeln('Бисмилляхир-рахманир-рахим. Альхамду лилляхи Раббиль-\'алямин. Ар-Рахманир-Рахим. Малики явмид-дин. Ийяка на\'буду ва ийяка наста\'ин. Ихдинас-сыраталь-мустакым. Сыраталь-лязина ан\'амта \'аляйхим, гайриль-магдуби \'аляйхим валяд-даллин.');
    translation.writeln('[Перевод Аль-Фатихи]');
    translation.writeln('Во имя Аллаха, Милостивого, Милосердного. Хвала Аллаху, Господу миров. Милостивому, Милосердному. Властелину Дня воздаяния. Тебе одному мы поклоняемся и Тебя одного молим о помощи. Веди нас прямым путем. Путем тех, кого Ты облагодетельствовал, не тех, на кого пал гнев, и не заблудших.');

    bool readZamm = !isFarz || rekat <= 2;
    if (readZamm) {
      DuaSurah zamm = _getZammISure(time, partName, rekat);
      arabic.writeln('\n====================\n');
      transcription.writeln('\n----------------------------------------\n');
      translation.writeln('\n----------------------------------------\n');

      arabic.writeln('[ДОПОЛНИТЕЛЬНАЯ СУРА (${zamm.name})]');
      arabic.writeln(zamm.arabic);
      transcription.writeln('[Сура ${zamm.name}]');
      transcription.writeln(zamm.transcription);
      translation.writeln('[Перевод ${zamm.name}]');
      translation.writeln(zamm.translation);
    }

    return {
      'arabic': arabic.toString(),
      'transcription': transcription.toString(),
      'translation': translation.toString(),
    };
  }

  static String _getKiyamNote(Mezhep mezhep, Gender gender) {
    if (mezhep == Mezhep.shafii) {
      return 'В Шафиитском мазхабе в 1-м ракаате вместо Субханаки читается Ваджджахту. В молитвах, читаемых вслух, Басмала произносится вслух.';
    }
    return 'Кыям — это стояние. Настоятельно рекомендуется смотреть на место земного поклона для концентрации.';
  }

  static String _getItidalNote(Mezhep mezhep, bool isSabahFarzSecondRekat) {
    String note = '';
    if (mezhep == Mezhep.shafii || mezhep == Mezhep.hanbali) {
      note = 'Поднимайте руки до уровня плеч при вставании (Раф\'уль Ядейн).';
    }
    if (isSabahFarzSecondRekat && mezhep == Mezhep.shafii) {
      note += ' В Шафиитском мазхабе во 2-м ракаате утренней молитвы (Фаджр) стоя читается мольба Кунут.';
    }
    return note.isNotEmpty ? note : 'Встаньте и сделайте короткую паузу, чтобы полностью выпрямиться.';
  }

  static String _getSecdeActionText(Gender gender) {
    if (gender == Gender.male) {
      return 'Опуститесь в земной поклон (Саджда). Лоб и нос касаются земли. Ступни остаются вертикальными, пальцы направлены к Кибле. Держите локти оторванными от земли и подальше от боков, а живот — подальше от бедер.';
    } else {
      return 'Опуститесь в земной поклон. Лоб и нос касаются земли. Держите локти прижатыми к телу и касающимися земли, живот близко к бедрам (сжатая поза).';
    }
  }

  static String _getOturusActionText(Mezhep mezhep, Gender gender, bool isLast) {
    if (gender == Gender.male) {
      if (isLast && (mezhep == Mezhep.shafii || mezhep == Mezhep.maliki || mezhep == Mezhep.hanbali)) {
        return 'В последнем сидении сядьте на левое бедро, левая нога выходит из-под правой ноги (Таваррук). Руки лежат на коленях.';
      }
      return 'Сядьте на левую ногу, держа правую ногу вертикально, пальцы направлены к Кибле (Ифтириш). Руки лежат на коленях.';
    } else {
      return 'В обоих сидениях садитесь на левое бедро, ноги выведены в правую сторону (Таваррук). Руки лежат на коленях, пальцы вместе.';
    }
  }

  static String _getOturusNote(Mezhep mezhep, bool isLast) {
    if (isLast) {
      return 'В последнем сидении прочтите мольбы Ташаххуд, Салли, Барик и Раббана.';
    }
    return 'В первом сидении прочтите только мольбу Ташаххуд (Ат-Тахият).';
  }

  static List<DuaSurah> getKiyamRecitationsList(
    Mezhep mezhep,
    PrayerTime time,
    String partName,
    int rekat,
    bool isFarz,
    bool isIkindiYatsi,
  ) {
    List<DuaSurah> list = [];
    final all = getDuaSurahs();

    if (rekat == 1) {
      if (mezhep == Mezhep.shafii) {
        list.add(DuaSurah(
          audioFileName: 'veccehtu.mp3',
          name: 'Ваджахту',
          arabic: 'وَجَّهْتُ وَجْهِيَ لِلَّذِي فَطَرَ السَّمَاوَاتِ وَالْأَرْضَ حَنِيفًا وَمَا أَنَا مِنَ الْمُشْرِكِينَ. إِنَّ صَلَاتِي وَنُسُكِي وَمَحْيَايَ وَمَمَاتِي لِلَّهِ رَبِّ الْعَالَمِينَ. لَا شَرِيكَ لَهُ وَبِذَٰلِكَ أُمِرْتُ وَأَنَا مِنَ الْمُسْلِمِينَ.',
          transcription: 'Ваджджахту ваджхия лиллязи фатарас-самавати валь-арда ханифан ва ма ана миналь-мушрикин. Инна саляти ва нусуки ва махяя ва мамати лилляхи раббиль-\'алямин. Ля шарика ляху ва бизалика умирту ва ана миналь-муслимин.',
          translation: 'Поистине, я обратил свое лицо к Тому, Кто сотворил небеса и землю, будучи ханифом, и я не из числа многобожников. Поистине, моя молитва, мое поклонение, моя жизнь и моя смерть принадлежат Аллаху, Господу миров. Нет у Него сотоварища. Это мне было повелено, и я из числа мусульман.',
          description: '',
        ));
      } else if (mezhep != Mezhep.maliki) {
        list.add(all.firstWhere((element) => element.name == 'Субханака'));
      }
    } else if (isIkindiYatsi && rekat == 3) {
      if (mezhep == Mezhep.hanafi || mezhep == Mezhep.hanbali) {
        list.add(all.firstWhere((element) => element.name == 'Субханака'));
      }
    }

    list.add(all.firstWhere((element) => element.name.contains('Фатиха')));

    bool readZamm = !isFarz || rekat <= 2;
    if (readZamm) {
      list.add(_getZammISure(time, partName, rekat));
    }

    return list;
  }

  static List<DuaSurah> getOturusRecitationsList(Mezhep mezhep, bool isLast) {
    final all = getDuaSurahs();
    if (isLast) {
      return [
        all.firstWhere((element) => element.name == 'Ат-Тахият'),
        all.firstWhere((element) => element.name == 'Аллахумма Салли'),
        all.firstWhere((element) => element.name == 'Аллахумма Барик'),
        all.firstWhere((element) => element.name.contains('Раббана')),
      ];
    } else {
      return [
        all.firstWhere((element) => element.name == 'Ат-Тахият'),
      ];
    }
  }
