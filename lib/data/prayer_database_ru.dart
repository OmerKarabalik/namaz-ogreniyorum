  // --- DYNAMIC PRAYER STEPS GENERATOR ---
  static Prayer getPrayer(Mezhep mezhep, Gender gender, PrayerTime time) {
    List<PrayerPart> parts = [];

    switch (time) {
      case PrayerTime.sabah:
        parts.add(_buildPart(mezhep, gender, '2 Ракаата Сунна', 2, false, time));
        parts.add(_buildPart(mezhep, gender, '2 Ракаата Фард', 2, true, time));
        break;
      case PrayerTime.ogle:
        parts.add(_buildPart(mezhep, gender, '4 Ракаата Первая Сунна', 4, false, time));
        parts.add(_buildPart(mezhep, gender, '4 Ракаата Фард', 4, true, time));
        parts.add(_buildPart(mezhep, gender, '2 Ракаата Последняя Сунна', 2, false, time));
        break;
      case PrayerTime.ikindi:
        parts.add(_buildPart(mezhep, gender, '4 Ракаата Сунна', 4, false, time, isIkindiYatsiSunnet: true));
        parts.add(_buildPart(mezhep, gender, '4 Ракаата Фард', 4, true, time));
        break;
      case PrayerTime.aksam:
        parts.add(_buildPart(mezhep, gender, '3 Ракаата Фард', 3, true, time));
        parts.add(_buildPart(mezhep, gender, '2 Ракаата Сунна', 2, false, time));
        break;
      case PrayerTime.yatsi:
        parts.add(_buildPart(mezhep, gender, '4 Ракаата Первая Сунна', 4, false, time, isIkindiYatsiSunnet: true));
        parts.add(_buildPart(mezhep, gender, '4 Ракаата Фард', 4, true, time));
        parts.add(_buildPart(mezhep, gender, '2 Ракаата Последняя Сунна', 2, false, time));
        if (mezhep == Mezhep.hanafi) {
          parts.add(_buildVitirHanafi(gender));
        } else {
          parts.add(_buildVitirOther(mezhep, gender));
        }
        break;
      case PrayerTime.cuma:
        if (mezhep == Mezhep.hanafi) {
          parts.add(_buildPart(mezhep, gender, '4 Ракаата Первая Сунна', 4, false, time));
          parts.add(_buildPart(mezhep, gender, '2 Ракаата Фард (В джамаате)', 2, true, time));
          parts.add(_buildPart(mezhep, gender, '4 Ракаата Последняя Сунна', 4, false, time));
        } else {
          parts.add(_buildPart(mezhep, gender, '2 Ракаата Первая Сунна', 2, false, time));
          parts.add(_buildPart(mezhep, gender, '2 Ракаата Фард (В джамаате)', 2, true, time));
          parts.add(_buildPart(mezhep, gender, '2 Ракаата Последняя Сунна', 2, false, time));
        }
        break;
      case PrayerTime.bayram:
        parts.add(_buildBayram(mezhep, gender));
        break;
      case PrayerTime.cenaze:
        parts.add(_buildCenaze(mezhep, gender));
        break;
    }

    return Prayer(
      time: time,
      description: _getPrayerDescription(time),
      parts: parts,
    );
  }

  static String _getPrayerDescription(PrayerTime time) {
    switch (time) {
      case PrayerTime.sabah: return 'Утренняя молитва (Фаджр) состоит из 2 ракаатов сунны и 2 ракаатов фарда.';
      case PrayerTime.ogle: return 'Полуденная молитва (Зухр) состоит из 4 ракаатов первой сунны, 4 фарда и 2 последней сунны.';
      case PrayerTime.ikindi: return 'Послеполуденная молитва (Аср) состоит из 4 ракаатов сунны и 4 фарда.';
      case PrayerTime.aksam: return 'Вечерняя молитва (Магриб) состоит из 3 ракаатов фарда и 2 сунны.';
      case PrayerTime.yatsi: return 'Ночная молитва (Иша) состоит из 4 ракаатов первой сунны, 4 фарда, 2 последней сунны и Витра.';
      case PrayerTime.cuma: return 'Пятничная молитва (Джума) совершается в джамаате во время полуденной молитвы в пятницу.';
      case PrayerTime.bayram: return 'Праздничная молитва состоит из 2 ракаатов, совершаемых в праздничное утро с дополнительными такбирами.';
      case PrayerTime.cenaze: return 'Погребальная молитва (Джаназа) совершается полностью стоя, с просьбами о прощении для умершего.';
    }
  }

